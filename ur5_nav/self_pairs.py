"""The self-collision pair table the planner uses, read from the C++ header.

`ompl::robots::UR5::selfPairs()` is the single source of truth: it is generated by
``scripts/generate_ur5_self_pairs.py`` and carries the margins calibrated against
PyBullet by ``scripts/calibrate_self_margins.py``. Anything on this side that decides
whether a configuration is acceptable to the planner has to read the same table, or it
answers a question the planner was never asked -- which is exactly how goals that the
exporter certified at h = +0.077 turned out to sit at +0.013 once the planner looked.

Parsing the header rather than re-deriving the table is deliberate. A second derivation
would be a second thing to keep in step, and the failure mode is silent: a stale copy
disagrees only on the configurations that matter.
"""

from __future__ import annotations

import os
import pathlib
import re
from dataclasses import dataclass

import numpy as np

# This package lives at <ompl>/ur5_experiments/ur5_nav/, so the headers are two levels up.
# Derived rather than hardcoded: this is a submodule, and a checkout somewhere else must
# still find the tables it is reading -- silently falling back to another clone's header
# would calibrate against a pair table that is not the one being built.
_OMPL_ROOT = pathlib.Path(__file__).resolve().parents[2]

DEFAULT_HEADER = os.environ.get(
    "OMPL_UR5_HEADER", str(_OMPL_ROOT / "src" / "ompl" / "robots" / "UR5.h")
)

DEFAULT_BARRIER_HEADER = os.environ.get(
    "OMPL_BARRIER_HEADER", str(_OMPL_ROOT / "src" / "ompl" / "cbf" / "ClearanceBarrier.h")
)

_PAIR = re.compile(r"\{\s*(\d+)\s*,\s*(\d+)\s*,\s*([\d.eE+-]+)\s*\}")
_SPHERE = re.compile(r"\{(\d+),\s*\{([^}]*)\},\s*([\d.eE+-]+),\s*\"([^\"]+)\"\}")


def load_self_buffer(header: str = DEFAULT_BARRIER_HEADER) -> float:
    """`ClearanceBarrier::defaultSelfBuffer` -- what a filter over-reserves on self rows.

    This is *not* the workspace buffer and must not be confused with it. The workspace
    buffer covers the SDF's interpolation error, which is a property of the grid; two
    spheres have no grid between them, so all this absorbs is step linearisation, and it
    is smaller by more than an order of magnitude. Judging a goal's self clearance against
    the workspace buffer rejects goals the planner would accept -- it rejected every goal
    in `pillars` and `clutter` at 15 mm where the planner asks for 1 mm.
    """
    with open(header) as handle:
        match = re.search(r"defaultSelfBuffer\s*=\s*([\d.eE+-]+)", handle.read())
    if match is None:
        raise RuntimeError(f"defaultSelfBuffer not found in {header}")
    return float(match.group(1))


@dataclass
class SelfPairs:
    """Sphere index pairs and their calibrated margins, in header order."""

    a: np.ndarray
    b: np.ndarray
    margin: np.ndarray
    radii: np.ndarray  # per *sphere*, used only to check the indices still line up

    def __len__(self) -> int:
        return len(self.a)

    def clearance(self, centers: np.ndarray) -> np.ndarray:
        """``|p_a - p_b| - r_a - r_b - margin`` for every pair, given sphere centres."""
        gap = np.linalg.norm(centers[self.a] - centers[self.b], axis=1)
        return gap - self.radii[self.a] - self.radii[self.b] - self.margin

    def check_alignment(self, radii: np.ndarray) -> None:
        """Fail loudly if this side's sphere order is not the header's.

        The table is indices into ``UR5::spheres()``. If the two orders ever diverge the
        pairs still evaluate -- against the wrong spheres -- so this is checked rather
        than assumed.
        """
        if len(radii) != len(self.radii) or not np.allclose(radii, self.radii, atol=1e-12):
            raise RuntimeError(
                "sphere order does not match the C++ table: the self-collision pairs "
                "would be evaluated against the wrong spheres"
            )


def load_self_pairs(header: str = DEFAULT_HEADER) -> SelfPairs:
    with open(header) as handle:
        source = handle.read()

    spheres = source.split("static const std::array<Sphere, nSpheres> table{{")[1]
    spheres = spheres.split("// clang-format on")[0]
    radii = np.array([float(r) for _, _, r, _ in _SPHERE.findall(spheres)])

    table = source.split("static const std::array<SelfPair, nSelfPairs> table{{")[1]
    table = table.split("// clang-format on")[0]
    rows = _PAIR.findall(table)
    if not rows:
        raise RuntimeError(f"no self pairs found in {header}")

    return SelfPairs(
        a=np.array([int(a) for a, _, _ in rows]),
        b=np.array([int(b) for _, b, _ in rows]),
        margin=np.array([float(m) for _, _, m in rows]),
        radii=radii,
    )
